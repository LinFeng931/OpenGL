void CAirplane::draw()
{
	if (_type != 4) {
		for (int j = 0; j < _blood; j++) {
			blood[j].setColor(glm::vec3(0.0f, 1.0f, 0.0f));
			blood[j].draw();
		}
	}
	else {
		for (int j = 0; j < _blood; j++) {
			blood[j].setColor(glm::vec3(1.0f, 0.0f, 1.0f));
			blood[j].draw();
		}
	}
	if (_blood > 0) {
		glUseProgram(_shaderProg);
		updateMatrix();
		glBindVertexArray(_vao);

		switch (_type)
		{
		case 1:
			glDrawElements(GL_TRIANGLES, type1_idxCount, GL_UNSIGNED_INT, 0);
			break;
		case 2:
			glDrawElements(GL_TRIANGLES, type2_idxCount, GL_UNSIGNED_INT, (void*)(type2_idxStart * sizeof(GLuint)));
			break;
		case 3:
			glDrawElements(GL_TRIANGLES, type3_idxCount, GL_UNSIGNED_INT, (void*)(type3_idxStart * sizeof(GLuint)));
			break;
		case 4:
			glDrawElements(GL_TRIANGLES, type4_idxCount, GL_UNSIGNED_INT, (void*)(type4_idxStart * sizeof(GLuint)));
			break;
		default:
			break;
		}
	}
	else {
		dead.draw();
	}
}

void CAirplane::update(float dt)
{
	switch (_type)
	{
	case 1:
		if (re_type != _type) {
			_skillTimer = 0.0f;
			re_color = glm::vec3(1.0f);
			setColor(re_color);
			re_type = _type;
			bullet_timer = 3.0f;
		}

		break;
	case 2: //導彈
		bullet_timer += dt;
		if (re_type != _type) {
			_skillTimer = 0.0f;
			re_color = glm::vec3(0.24f, 0.92f, 0.83f);
			setColor(re_color);
			re_type = _type;
		}
		_skillTimer += dt;
		if (_skillTimer >= 5.0f) {
			setType(0);
			_skillTimer = 0.0f;
		}

		break;
	case 3: //雙倍攻擊
		if (re_type != _type) {
			_skillTimer = 0.0f;
			re_color = glm::vec3(0.92f, 0.34f, 0.24f);
			setColor(re_color);
			re_type = _type;
		}

		_skillTimer += dt;
		if (_skillTimer >= 6.0f) {
			setType(0);
			_skillTimer = 0.0f;
		}
		break;
	case 4: //額外生命
		if (re_type != _type) {
			_skillTimer = 0.0f;
			re_color = glm::vec3(0.8f, 0.94f, 0.04f);
			setColor(re_color);
			re_type = _type;
		}

		if (_skillOn == false) {
			normal_blood = _blood;
			_blood = 6;
			_skillOn = !_skillOn;
		}

		_skillTimer += dt;
		if (_skillTimer >= 6.0f) {
			setType(0);
			_skillTimer = 0.0f;
			_blood = normal_blood;
			_skillOn = !_skillOn;
		}
		break;
	default:
		re_color = glm::vec3(1.0f);
		setColor(re_color);
		break;
	}

	for (int i = 0; i < _blood; i++) {
		blood[i].setPos(glm::vec3(_pos.x + 0.1f * i, _pos.y - 0.7f, 0.0f));
		blood[i].setPos(glm::vec3(blood[i].getPos().x - 0.17f, blood[i].getPos().y, 0.0f));
	}

	if (_isflashing && _blood > 0) {
		flashTimer += dt;
		if (flashTimer >= nextTime) {
			_flashOn = !_flashOn;
			if (_flashOn) setColor(glm::vec3(0.0f));
			else setColor(re_color);
			nextTime += 0.1f;
		}
	}
	if (nextTime > 0.5f) {
		_isflashing = false;
		flashTimer = 0.0f;
		nextTime = 0.0f;
		setColor(glm::vec3(re_color));
	}

	if (_blood == 0 && _type != 3) {
		_deadtime += dt;
		dead.setPos(_pos);
		dead.update(dt);
		if (_deadtime >= 1.0f) _blood--;
	}

	if (_blood == 0 && _type == 3) {
		setType(0);
	}
}

