bool CAirplane::checkCollision(glm::vec3 pos, float otherRadius) {
	float dx = pos[0] - _pos.x;
	float dy = pos[1] - _pos.y;
	float combineRadius = circleRadius + otherRadius;
	if ((dx * dx + dy * dy) <= (combineRadius * combineRadius) && _blood > 0) {
		return(true);
	}
	else return(false);
}

