void CVillain::Moving(float dt) {
	glm::vec3 pos = getPos();

	if (pos.x >= -3.5f && PosX == true) {
		pos.x -= _speed * dt;
	}
	else{
		PosX = false;
		pos.x += _speed * dt;
		if (pos.x >= 3.5f) PosX = true;
	}
	
	if (pos.y >= 1.0f && PosY == true) {
		pos.y -= 0.5f * _speed * dt;
	}
	else {
		PosY = false;
		pos.y += 0.5f * _speed * dt;
		if (pos.y >= 3.5f) PosY = true;
	}
	
	setPos(pos);
}

int CVillain::getStatus() {
	if (_blood < 0) {
		return(-1);
	}
	else if (_blood == 0) {
		return(0);
	}
	else if (_blood <= 2) {
		return(1);
	}
	else if (_blood <= 4) {
		return(2);
	}
}

